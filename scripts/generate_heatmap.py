import geoip2.database

# Carica database GeoLite2 locale
reader = geoip2.database.Reader("data/GeoLite2-City.mmdb")

points = []

def add_ip(ip, intensity, src):
    try:
        r = reader.city(ip)
        lat = r.location.latitude
        lon = r.location.longitude
        if lat and lon:
            points.append({
                "lat": lat,
                "lon": lon,
                "intensity": intensity,
                "src": src
            })
    except:
        pass

